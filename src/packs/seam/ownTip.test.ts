/**
 * The own-tip rule, against SEAM's own kept set for a real neuron.
 *
 * `__fixtures__/ownTipNeuron.json` is one neuron of the rv2 set — every one of its 505 open
 * ends, six of its candidate lists, and what SEAM kept from each, **read out of the published
 * `candidates.parquet` rather than recomputed**. The lists are the ones that make the rule do
 * something: one that keeps most of what it found, two that keep nothing at all, and one that
 * gives nine tenths of what was near enough to a nearer end.
 *
 * **A golden rather than a hand-written expectation, for this file's whole reason.** Every way
 * of getting the rule slightly wrong leaves a *plausible* list — dropping the second test keeps
 * a few extra candidates, comparing to the end's unsnapped position moves a handful across the
 * limit, renumbering in the wrong order gives the same set with the ranks shuffled. None of
 * those looks like a failure anywhere downstream; each one is simply a different answer than
 * the fit was made against. An expectation written from the same reading as the code would
 * agree with it — which is exactly what a golden generated by a second implementation of the
 * rule would be, and why `make_search.py` reads SEAM's answer instead of computing one. The rule
 * is also the one piece of the search that is not vendored from SEAM, so this stands in for the
 * byte comparison `pnpm vendor:seam` gives the rest.
 *
 * The tips cross as a `Float32Array`, which is what `Tips.positions` is: the fixture's numbers
 * are float64 and the narrowing is part of what is being checked, since the second test is a
 * comparison between two nearly equal distances.
 */

import { describe, expect, it } from 'vitest'

import manifest from './__fixtures__/fixture.json'
import neuron from './__fixtures__/ownTipNeuron.json'
import type { EndCandidates } from './ownTip'
import { OWN_TIP_UM, ownTipRule } from './ownTip'

const tipsNm = Float32Array.from(neuron.tipsNm.flat())

type Golden = (typeof neuron.lists)[number]

function listOf(one: Golden): EndCandidates {
  return {
    tip: one.tip,
    rows: one.geoRank.length,
    columns: {
      contact_x_nm: Float64Array.from(one.contactNm.map((p) => p[0]!)),
      contact_y_nm: Float64Array.from(one.contactNm.map((p) => p[1]!)),
      contact_z_nm: Float64Array.from(one.contactNm.map((p) => p[2]!)),
      geo_rank: Float64Array.from(one.geoRank),
    },
  }
}

const lists = neuron.lists.map(listOf)
const answers = ownTipRule(tipsNm, lists, neuron.own_um)

describe('the own-tip rule, against SEAM', () => {
  /**
   * Against the **manifest**, not against the golden's own copy. `ownTipNeuron.json` takes
   * `own_um` from `fixture.json` too, so comparing the two would be the generator agreeing with
   * itself; `fixture.json` is SEAM's published record of what the set was fitted with, and is
   * the same file `suggestionSet.ts` reads the `shown` cutoff out of rather than writing it
   * down. If SEAM refits the limit, this is what notices.
   */
  it('uses the limit SEAM fitted the set with', () => {
    expect(OWN_TIP_UM).toBe(manifest.pipeline.own_tip.own_um)
    expect(neuron.own_um).toBe(manifest.pipeline.own_tip.own_um)
  })

  /**
   * `kept` is in SEAM's renumbered `geo_rank` order, so comparing the whole array in order is
   * what pins the renumbering as well as the set — a list that kept the right candidates and
   * ranked them the other way round fails here, not only in the order check below.
   */
  for (const [at, golden] of neuron.lists.entries()) {
    it(`end ${golden.end_uid} keeps what SEAM kept — ${golden.why}`, () => {
      expect([...answers[at]!.kept]).toEqual(golden.kept)
    })
  }

  /**
   * The two reasons are counted apart because they are two different stories about an end: a
   * list that found nothing within 2 µm is an end with no neurite near it, and a list that
   * found plenty and gave it all to a neighbour is an end that is not the one those pieces
   * attach to. A reader asking why a tip has no candidates wants to be told which.
   */
  it('splits the dropped rows between the two tests', () => {
    expect(
      answers.map((one) => ({ tooFar: one.tooFar, anothersTip: one.anothersTip })),
    ).toEqual(neuron.lists.map((one) => ({ tooFar: one.tooFar, anothersTip: one.anothersTip })))
    for (const [at, one] of answers.entries()) {
      expect(one.kept.length + one.tooFar + one.anothersTip).toBe(lists[at]!.rows)
    }
  })

  /** The renumbering: position in `kept` plus one, so the ranks must ascend with SEAM's. */
  it('renumbers in the search’s own order', () => {
    for (const [at, one] of answers.entries()) {
      const ranks = [...one.kept].map((i) => lists[at]!.columns['geo_rank']![i]!)
      expect(ranks).toEqual([...ranks].sort((a, b) => a - b))
    }
  })

  /**
   * The renumbering reads the `geo_rank` column rather than the row order, so a list handed
   * over shuffled gets the same answer. Worth pinning because the reverse — reading the order
   * and ignoring the column — is indistinguishable on every list the search itself produces,
   * which always arrive already sorted.
   */
  it('answers the same when the rows arrive in another order', () => {
    const golden = neuron.lists[0]!
    const back = (i: number) => golden.geoRank.length - 1 - i
    const flipped = listOf({
      ...golden,
      contactNm: [...golden.contactNm].reverse(),
      geoRank: [...golden.geoRank].reverse(),
    })
    const [answer] = ownTipRule(tipsNm, [flipped], neuron.own_um)
    expect([...answer!.kept].map(back)).toEqual(golden.kept)
  })

  /**
   * The silent half of the rule, and the reason the function takes the tips rather than deriving
   * them from the lists: a contact may be nearest to an end whose own list is not in hand.
   *
   * **Constructed, not SEAM's own instance.** This neuron's 505 ends were all searched, so the
   * case is made by narrowing the fixture to the six tips its lists belong to and showing that
   * more survives. SEAM's real instance is end 1967 on another neuron — the one open end of
   * 2,708 with no list — which takes 42 candidates off three of its neighbours. Covering that
   * would mean a second neuron's lists in the fixture, which is a lot of file for one case the
   * narrowing already exercises the same way round.
   */
  it('drops candidates that belong to a tip with no list of its own', () => {
    const searched = new Set(lists.map((one) => one.tip))
    const onlySearched = new Float32Array(searched.size * 3)
    const renumbered = new Map<number, number>()
    for (const tip of searched) {
      const at = renumbered.size
      renumbered.set(tip, at)
      onlySearched.set(tipsNm.subarray(tip * 3, tip * 3 + 3), at * 3)
    }
    const narrowed = ownTipRule(
      onlySearched,
      lists.map((one) => ({ ...one, tip: renumbered.get(one.tip)! })),
      neuron.own_um,
    )
    const kept = (all: readonly { kept: Int32Array }[]) =>
      all.reduce((total, one) => total + one.kept.length, 0)
    expect(kept(narrowed)).toBeGreaterThan(kept(answers))
  })
})

/**
 * Two tips at one place, which the snap makes possible and rv2 happens not to contain.
 *
 * Built by hand for that reason: no neuron in the set has two tips at one position, and none of
 * its 141,980 near-enough contacts is equidistant from two — so the golden cannot exercise it,
 * and without this the k-d tree's arbitrary tie-break would go unnoticed until a neuron with a
 * short spur arrived. The failure it guards is quiet: one of the pair loses *every* candidate
 * it shares with the other, which reads downstream as an end with nothing near it.
 */
describe('two tips at the same place', () => {
  /*
   * Seventeen tips, with 8 moved onto 0. The count and the spread are not decoration: a tree
   * over three points answers the lower index by luck, and a test built on that passes whether
   * the tie is handled or not — which the first draft of this block did. At seventeen the tree
   * branches, and its traversal reaches **8** first, so the arbitrary answer and the right one
   * are different numbers.
   */
  const COINCIDE = [0, 8]
  const together = new Float32Array(17 * 3)
  for (let i = 0; i < 17; i++) {
    together.set([i * 1000, (i % 3) * 700, (i % 5) * 400], i * 3)
  }
  together.set(together.subarray(0, 3), COINCIDE[1]! * 3)

  const listAt = (tip: number): EndCandidates => ({
    tip,
    rows: 1,
    columns: {
      // A nanometre off the shared position, so both tips are far inside the 2 µm limit.
      contact_x_nm: Float64Array.from([1]),
      contact_y_nm: Float64Array.from([0]),
      contact_z_nm: Float64Array.from([0]),
      geo_rank: Float64Array.from([1]),
    },
  })

  it('gives the shared candidate to exactly one of them', () => {
    const [low, high] = ownTipRule(together, COINCIDE.map(listAt))
    expect(low!.kept.length + high!.kept.length).toBe(1)
  })

  /**
   * Which one is not arbitrary: SEAM asks `cKDTree.query`, which answers the lowest index, so
   * the lower tip takes it. The k-d tree on its own names whichever the traversal reached
   * first — here the higher — which is a property of the tree's shape, not of the data.
   */
  it('gives it to the lower tip, as SEAM’s own index does', () => {
    const [low, high] = ownTipRule(together, COINCIDE.map(listAt))
    expect([...low!.kept]).toEqual([0])
    expect([...high!.kept]).toEqual([])
    expect(high!.anothersTip).toBe(1)
  })

  /** The order the lists are handed over in must not decide it either. */
  it('answers the same whichever list comes first', () => {
    const [high, low] = ownTipRule(together, [...COINCIDE].reverse().map(listAt))
    expect([...low!.kept]).toEqual([0])
    expect([...high!.kept]).toEqual([])
  })
})

describe('refusals', () => {
  it('refuses a list at a tip outside the set it was given', () => {
    expect(() => ownTipRule(tipsNm, [{ ...lists[0]!, tip: 10_000 }])).toThrow(
      /not one of the 505 tips/,
    )
  })

  /**
   * A column SEAM renamed or dropped arrives as `undefined`, and a rule that read nothing out
   * of it would keep every candidate — a full answer with no symptom anywhere downstream.
   */
  it('refuses a list missing one of SEAM’s columns', () => {
    const { contact_z_nm: _gone, ...rest } = lists[0]!.columns
    expect(() => ownTipRule(tipsNm, [{ ...lists[0]!, columns: rest }])).toThrow(
      /no "contact_z_nm" column/,
    )
  })

  it('refuses a column that is not as long as the list says', () => {
    const columns = { ...lists[0]!.columns, geo_rank: new Float64Array(3) }
    expect(() => ownTipRule(tipsNm, [{ ...lists[0]!, columns }])).toThrow(
      /says 100 rows and its "geo_rank" column has 3/,
    )
  })

  /**
   * One list per end. Two at one tip would each keep what they share — the double-scoring the
   * rule exists to prevent, arriving as two ordinary-looking answers.
   */
  it('refuses two lists at the same tip', () => {
    expect(() => ownTipRule(tipsNm, [lists[0]!, { ...lists[1]!, tip: lists[0]!.tip }])).toThrow(
      /Two candidate lists are at tip/,
    )
  })

  /** Checked before anything is built, so a caller walking a set pays for no trees first. */
  it('checks every list before it builds an index', () => {
    expect(() => ownTipRule(tipsNm, [lists[0]!, { ...lists[1]!, tip: -1 }])).toThrow(/tip -1/)
  })
})
