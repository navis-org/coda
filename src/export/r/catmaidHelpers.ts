/**
 * The generated R a CATMAID dataset needs: `coda_catmaid_dataset`, one project on one server,
 * read through the natverse's rcatmaid, and the functions that ask it.
 *
 * The R twin of the notebook's `CodaCatmaidDataset` (`python/catmaidHelpers.ts`), and checked
 * the same way: `pnpm probe:catmaid` knits nothing, it sources the document's chunks and
 * compares every output with the canvas. A dataset is an **environment**, so the neuron table
 * is built once and shared by every chunk reading it, as the notebook's object holds it.
 *
 * What it adds to rcatmaid is the neuron table — Coda's `type` is derived from the project's
 * meta-annotations (`data/catmaid/annotations.ts`). The walk is `coda_walk`, shared with neuPrint's
 * (`emitters/connectivity.ts`). Five things in it are there because rcatmaid's obvious call
 * answers a different question:
 *
 * - **`catmaid_skids("name:.")` is not the project's skeleton list** — 1,132,353 on FAFB, where
 *   the canvas's `skeletons/` lists 5,601 — so the list is read from that endpoint directly.
 * - **`catmaid_query_meta_annotations` errors on an annotation the project does not have**, which
 *   on L1 is both conventions, so a missing one is caught and means none.
 * - **`catmaid_get_connector_table` is one row per partner by default**; `partner.skids = FALSE`
 *   is the connector *links* the canvas reads, one per site.
 * - **An empty id vector is no constraint at all**: rcatmaid builds no `skeleton_ids` field from
 *   it, so the server answers for every skeleton. An empty side answers empty before asking.
 * - **`skeletons/summary` is a direct fetch**, and like the canvas a refusal of it leaves the
 *   node count and cable length empty rather than the table unbuilt.
 *
 * And one difference that is kept: rcatmaid reads annotations through `annotations/
 * forskeletons`, which orders a neuron's labels differently from the `annotationlist` the canvas
 * reads, so the joined `annotations` cell holds the same labels in another order. CATMAID's
 * annotations are a bag, and the one place order could matter — a neuron carrying two
 * meta-annotated names, where the first is the instance — does not occur on either VFB project.
 */

import { registerHelper } from './registry'

registerHelper({
  name: 'coda_catmaid_dataset',
  needs: ['coda_walk'],
  requires: ['catmaid', 'dplyr'],
  source: [
    'coda_catmaid_dataset <- function(server, project_id, token = NULL) {',
    "  # Coda's CATMAID dataset: one project on one CATMAID server, read through rcatmaid.",
    '  #',
    '  # An environment, so the neuron table is built once and shared by every chunk that reads it',
    '  # (coda_catmaid_labels). Every call names this connection and project, so two CATMAID',
    '  # datasets in one document never answer for each other.',
    '  ds <- new.env()',
    '  ds$conn <- catmaid::catmaid_login(',
    '    server = server,',
    '    token = if (is.null(token) || !nzchar(token)) NULL else token',
    '  )',
    '  ds$pid <- as.integer(project_id)',
    '  ds',
    '}',
    '',
    'coda_catmaid_meta_members <- function(ds, meta) {',
    '  # Names of the annotations meta-annotated with `meta`; none if the project has no such',
    '  # annotation, which rcatmaid reports as an error.',
    '  found <- tryCatch(',
    '    catmaid::catmaid_query_meta_annotations(meta, pid = ds$pid, conn = ds$conn),',
    '    error = function(e) NULL',
    '  )',
    '  if (is.null(found) || nrow(found) == 0) return(character(0))',
    '  found$name[found$type == "annotation"]',
    '}',
    '',
    'coda_catmaid_labels <- function(ds) {',
    '  # The neuron table Coda builds for the project, one row per skeleton: neuronId (the',
    '  # skeleton id, as text), name, type, instance, ontologyId, the remaining annotations joined',
    '  # with "; ", and the node count and cable length (nm). `instance` is the annotation',
    '  # meta-annotated "neuron name" and `type` the part of it before "#"; `ontologyId` is the',
    '  # one meta-annotated "Cell type". A project that meta-annotates no neuron names (L1) uses',
    "  # each neuron's name as its type.",
    '  if (!is.null(ds$labels)) return(ds$labels)',
    '  skids <- sort(as.integer(unlist(',
    '    catmaid::catmaid_fetch(paste0("/", ds$pid, "/skeletons/"), conn = ds$conn)',
    '  )))',
    '  names <- catmaid::catmaid_get_neuronnames(skids, pid = ds$pid, conn = ds$conn)',
    '  annotations <- catmaid::catmaid_get_annotations_for_skeletons(skids, pid = ds$pid, conn = ds$conn)',
    '  typed <- coda_catmaid_meta_members(ds, "neuron name")',
    '  ontology <- coda_catmaid_meta_members(ds, "Cell type")',
    '  # Node count and cable length; rcatmaid has no wrapper for this endpoint. A server that',
    '  # refuses it leaves the two columns empty rather than the table unbuilt, as on the canvas.',
    '  body <- stats::setNames(as.list(skids), sprintf("skeleton_ids[%d]", seq_along(skids) - 1L))',
    '  summaries <- tryCatch(',
    '    catmaid::catmaid_fetch(',
    '      paste0("/", ds$pid, "/skeletons/summary"), body = body, conn = ds$conn,',
    '      include_headers = FALSE',
    '    ),',
    '    error = function(e) {',
    '      message("No node counts or cable lengths: ", conditionMessage(e))',
    '      list()',
    '    }',
    '  )',
    '  by_skid <- split(annotations$annotation, annotations$skid)',
    '',
    '  rows <- lapply(skids, function(skid) {',
    '    key <- as.character(skid)',
    '    labels <- by_skid[[key]]',
    '    if (is.null(labels)) labels <- character(0)',
    '    # A label naming the instance is never also the ontology term, and the first of each wins.',
    '    is_typed <- labels %in% typed',
    '    is_term <- !is_typed & labels %in% ontology',
    '    instance <- labels[is_typed][1]',
    '    term <- labels[is_term][1]',
    '    rest <- unique(labels[!is_typed & !is_term])',
    '    name <- unname(names[key])',
    '    kind <- if (!is.na(instance)) sub("#.*$", "", instance) else if (length(typed)) NA_character_ else name',
    '    summary <- summaries[[key]]',
    '    list(',
    '      neuronId = key,',
    '      name = name,',
    '      type = kind,',
    '      instance = instance,',
    '      ontologyId = term,',
    '      annotations = if (length(rest)) paste(rest, collapse = "; ") else NA_character_,',
    '      nodes = if (is.null(summary$num_nodes)) NA_integer_ else as.integer(summary$num_nodes),',
    '      cableLength = if (is.null(summary$cable_length)) NA_real_ else as.numeric(summary$cable_length)',
    '    )',
    '  })',
    '  ds$labels <- dplyr::bind_rows(rows)',
    '  ds$labels',
    '}',
    '',
    'coda_catmaid_lookup <- function(ds, ids) {',
    "  # The neuron table's rows for these skeleton ids.",
    '  labels <- coda_catmaid_labels(ds)',
    '  labels[labels$neuronId %in% as.character(ids), ]',
    '}',
    '',
    'coda_catmaid_types <- function(ds, ids) {',
    '  labels <- coda_catmaid_labels(ds)',
    '  labels$type[match(as.character(ids), labels$neuronId)]',
    '}',
    '',
    'coda_catmaid_partners <- function(ds, connected, way, min_weight, keep = NULL) {',
    '  # One row per (queried skeleton, partner) with at least min_weight synapses, every',
    '  # confidence counted, oriented presynaptic to postsynaptic. `connected` is one',
    '  # catmaid_query_connected() answer, which holds both directions. With `keep`, only',
    '  # partners in it.',
    '  table <- connected[[if (way == "downstream") "outgoing" else "incoming"]]',
    '  if (is.null(table)) table <- data.frame(skid = integer(0), partner = integer(0), syn.count = integer(0))',
    '  table <- table[table$syn.count >= max(1, min_weight), ]',
    '  if (!is.null(keep)) table <- table[as.character(table$partner) %in% keep, ]',
    '  near <- as.character(table$skid)',
    '  far <- as.character(table$partner)',
    '  pre <- if (way == "downstream") near else far',
    '  post <- if (way == "downstream") far else near',
    '  tibble::tibble(',
    '    preId = pre, preType = coda_catmaid_types(ds, pre),',
    '    postId = post, postType = coda_catmaid_types(ds, post),',
    '    weight = as.integer(table$syn.count)',
    '  )',
    '}',
    '',
    'coda_catmaid_connectivity <- function(ds, seed_ids, direction, hops = 1, min_weight = 1,',
    '                                      include_fragments = FALSE) {',
    "  # Find partners hop by hop, as Coda's Connectivity node does. Without include_fragments, a",
    "  # partner must be in the neuron table (seeds are exempt): a project's synapses also reach",
    '  # skeletons its skeleton list does not hold.',
    '  keep <- if (include_fragments) NULL else union(coda_catmaid_labels(ds)$neuronId, as.character(seed_ids))',
    '  # One request per hop: a walk going both ways asks about the same skeletons twice.',
    '  last <- list(ids = NULL, connected = NULL)',
    '  coda_walk(seed_ids, direction, hops, function(ids, way) {',
    '    if (!identical(last$ids, ids)) {',
    '      last <<- list(ids = ids, connected = catmaid::catmaid_query_connected(',
    '        as.integer(ids), minimum_synapses = 1L, minimum_confidence = 1L,',
    '        pid = ds$pid, conn = ds$conn',
    '      ))',
    '    }',
    '    coda_catmaid_partners(ds, last$connected, way, min_weight, keep)',
    '  })',
    '}',
    '',
    'coda_catmaid_adjacency <- function(ds, sources, targets, by_type = FALSE) {',
    '  # Synapse counts from each source onto each target: the matrix (sources down, targets',
    '  # across, each once in the order given) and its non-zero cells as links. With by_type, lines',
    '  # are summed per type, and a neuron with no type keeps its own id.',
    '  rows <- unique(as.character(sources))',
    '  cols <- unique(as.character(targets))',
    '  counts <- matrix(0, length(rows), length(cols), dimnames = list(rows, cols))',
    '  if (length(rows) && length(cols)) {',
    '    found <- catmaid::catmaid_adjacency_matrix(as.integer(rows), as.integer(cols), pid = ds$pid, conn = ds$conn)',
    '    counts[] <- found[rows, cols, drop = FALSE]',
    '  }',
    "  # Each line's key and the (id, type) it stands for: grouped, a typed neuron joins its type's",
    '  # line, which has no id, and an untyped one keeps its own id and has no type.',
    '  ids <- unique(c(rows, cols))',
    '  types <- coda_catmaid_types(ds, ids)',
    '  typed <- by_type & !is.na(types) & types != ""',
    '  keys <- ifelse(typed, types, ids)',
    '  line_id <- stats::setNames(ifelse(typed, NA_character_, ids), keys)',
    '  line_type <- stats::setNames(types, keys)',
    '  if (by_type) {',
    '    row_keys <- keys[match(rownames(counts), ids)]',
    '    col_keys <- keys[match(colnames(counts), ids)]',
    '    counts <- rowsum(counts, factor(row_keys, levels = unique(row_keys)))',
    '    counts <- t(rowsum(t(counts), factor(col_keys, levels = unique(col_keys))))',
    '  }',
    '  cells <- which(counts > 0, arr.ind = TRUE)',
    '  cells <- cells[order(cells[, "row"], cells[, "col"]), , drop = FALSE]',
    '  pre <- rownames(counts)[cells[, "row"]]',
    '  post <- colnames(counts)[cells[, "col"]]',
    '  links <- tibble::tibble(',
    '    preId = unname(line_id[pre]), preType = unname(line_type[pre]),',
    '    postId = unname(line_id[post]), postType = unname(line_type[post]),',
    '    weight = as.integer(counts[cells])',
    '  )',
    '  list(matrix = counts, links = links)',
    '}',
    '',
    'coda_catmaid_synapses <- function(ds, ids, polarity = NULL, min_confidence = 0) {',
    '  # One row per connector link: neuronId, type, connectorId, polarity, confidence, x/y/z in',
    '  # nm. A connector is one presynaptic site, so this is one row per site.',
    '  sides <- if (is.null(polarity)) c("pre", "post") else polarity',
    '  # An empty id list would ask the server for every link: answer it with no rows instead.',
    '  if (length(ids) == 0) sides <- character(0)',
    '  parts <- lapply(sides, function(side) {',
    '    links <- catmaid::catmaid_get_connector_table(',
    '      as.integer(ids), direction = if (side == "pre") "outgoing" else "incoming",',
    '      partner.skids = FALSE, pid = ds$pid, conn = ds$conn',
    '    )',
    '    if (is.null(links) || nrow(links) == 0) return(NULL)',
    '    tibble::tibble(',
    '      neuronId = as.character(links$skid), connectorId = as.numeric(links$connector_id),',
    '      polarity = side, confidence = as.integer(links$confidence),',
    '      x = as.numeric(links$x), y = as.numeric(links$y), z = as.numeric(links$z)',
    '    )',
    '  })',
    '  out <- dplyr::bind_rows(parts)',
    '  if (nrow(out) == 0) {',
    '    out <- tibble::tibble(neuronId = character(0), connectorId = numeric(0), polarity = character(0),',
    '                          confidence = integer(0), x = numeric(0), y = numeric(0), z = numeric(0))',
    '  }',
    '  if (min_confidence > 0) out <- out[out$confidence >= min_confidence, ]',
    '  out <- tibble::add_column(out, type = coda_catmaid_types(ds, out$neuronId), .after = "neuronId")',
    '  out',
    '}',
    '',
    'coda_catmaid_synapses_between <- function(ds, sources = NULL, targets = NULL, location = "pre",',
    '                                          min_confidence = 0, include_fragments = TRUE) {',
    '  # Every synapse from a source onto a target, one row per pre/post link pair on a connector,',
    "  # at the connector. neuronId is the presynaptic end; confidence is the drawn end's link.",
    '  # With only one side given, the other is every partner on its connectors -- only those in',
    '  # the neuron table, unless include_fragments.',
    '  if (is.null(sources) && is.null(targets)) {',
    '    stop("Synapses between two sets needs sources, targets or both.")',
    '  }',
    "  # A side given but empty would drop that side's constraint from the query, answering every",
    '  # synapse of the other side: an empty set of neurons has no synapses instead.',
    '  empty <- (!is.null(sources) && length(sources) == 0) || (!is.null(targets) && length(targets) == 0)',
    '  pairs <- if (empty) NULL else catmaid::catmaid_get_connectors_between(',
    '    pre_skids = if (is.null(sources)) NULL else as.integer(sources),',
    '    post_skids = if (is.null(targets)) NULL else as.integer(targets),',
    '    pid = ds$pid, conn = ds$conn',
    '  )',
    '  if (is.null(pairs) || nrow(pairs) == 0) {',
    '    pairs <- data.frame(',
    '      pre_skid = integer(0), post_skid = integer(0), pre_confidence = integer(0),',
    '      post_confidence = integer(0), connector_x = numeric(0), connector_y = numeric(0),',
    '      connector_z = numeric(0)',
    '    )',
    '  }',
    '  if (!include_fragments && xor(is.null(sources), is.null(targets))) {',
    '    open <- if (is.null(sources)) pairs$pre_skid else pairs$post_skid',
    '    pairs <- pairs[as.character(open) %in% coda_catmaid_labels(ds)$neuronId, ]',
    '  }',
    '  if (min_confidence > 0) {',
    '    pairs <- pairs[pairs$pre_confidence >= min_confidence & pairs$post_confidence >= min_confidence, ]',
    '  }',
    '  drawn <- if (identical(location, "post")) "post" else "pre"',
    '  pre <- as.character(pairs$pre_skid)',
    '  post <- as.character(pairs$post_skid)',
    '  tibble::tibble(',
    '    neuronId = pre, type = coda_catmaid_types(ds, pre),',
    '    partnerId = post, partnerType = coda_catmaid_types(ds, post),',
    '    polarity = rep(drawn, length(pre)),',
    '    confidence = as.integer(if (drawn == "post") pairs$post_confidence else pairs$pre_confidence),',
    '    x = as.numeric(pairs$connector_x), y = as.numeric(pairs$connector_y), z = as.numeric(pairs$connector_z)',
    '  )',
    '}',
    '',
    'coda_catmaid_skeletons <- function(ds, ids) {',
    '  # The traced skeletons, as a nat neuronlist in nm. The soma is the node tagged "soma".',
    '  if (length(ids) == 0) return(nat::neuronlist())',
    '  catmaid::read.neurons.catmaid(as.integer(ids), pid = ds$pid, conn = ds$conn)',
    '}',
    '',
    'coda_catmaid_volumes <- function(ds, names = NULL) {',
    '  # Neuropil meshes by name, as a named list of mesh3d; every volume in the project if NULL.',
    '  if (is.null(names)) {',
    '    names <- catmaid::catmaid_get_volumelist(pid = ds$pid, conn = ds$conn)$name',
    '  }',
    '  stats::setNames(lapply(names, function(name) {',
    '    catmaid::catmaid_get_volume(name, pid = ds$pid, conn = ds$conn)',
    '  }), names)',
    '}',
  ],
})
